// Package contracts_test guards the pinned OpenAPI snapshots. It fails if a snapshot changes
// without its PROVENANCE.md record being updated to match, so a refreshed contract cannot land
// with a stale checksum, version, or retrieval date.
package contracts_test

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"
)

type snapshot struct {
	name       string
	spec       string
	provenance string
	// version is read out of the document itself so the assertion catches an upstream version bump
	// that the provenance record was not updated for.
	documentVersion func(t *testing.T, raw []byte) string
}

func snapshots() []snapshot {
	return []snapshot{
		{
			name:       "admin",
			spec:       filepath.Join("..", "admin", "openapi.json"),
			provenance: filepath.Join("..", "admin", "PROVENANCE.md"),
			documentVersion: func(t *testing.T, raw []byte) string {
				t.Helper()
				var doc struct {
					OpenAPI string `json:"openapi"`
					Info    struct {
						Version string `json:"version"`
					} `json:"info"`
				}
				if err := json.Unmarshal(raw, &doc); err != nil {
					t.Fatalf("parse admin contract: %v", err)
				}
				if doc.OpenAPI == "" {
					t.Fatal("admin contract has no openapi version")
				}
				return doc.Info.Version
			},
		},
		{
			name:       "cloud",
			spec:       filepath.Join("..", "cloud", "openapi.yaml"),
			provenance: filepath.Join("..", "cloud", "PROVENANCE.md"),
			documentVersion: func(t *testing.T, raw []byte) string {
				t.Helper()
				// The cloud contract is small and hand-maintained upstream; a regexp over the
				// info block avoids adding a YAML dependency to this guard.
				match := regexp.MustCompile(`(?m)^info:\n(?:  .*\n)*?  version: (\S+)`).FindSubmatch(raw)
				if match == nil {
					t.Fatal("cloud contract has no info.version")
				}
				return string(match[1])
			},
		},
	}
}

func TestSnapshotChecksumsMatchProvenance(t *testing.T) {
	for _, s := range snapshots() {
		t.Run(s.name, func(t *testing.T) {
			raw, err := os.ReadFile(s.spec)
			if err != nil {
				t.Fatalf("read contract: %v", err)
			}
			digest := sha256.Sum256(raw)
			want := hex.EncodeToString(digest[:])

			provenance, err := os.ReadFile(s.provenance)
			if err != nil {
				t.Fatalf("read provenance: %v", err)
			}
			if !strings.Contains(string(provenance), want) {
				t.Errorf("%s contract SHA-256 is %s, which does not appear in %s.\n"+
					"If you refreshed the contract, update its provenance record: checksum, "+
					"advertised version, upstream revision, and retrieval date.", s.name, want, s.provenance)
			}
		})
	}
}

func TestSnapshotVersionsMatchProvenance(t *testing.T) {
	for _, s := range snapshots() {
		t.Run(s.name, func(t *testing.T) {
			raw, err := os.ReadFile(s.spec)
			if err != nil {
				t.Fatalf("read contract: %v", err)
			}
			version := s.documentVersion(t, raw)

			provenance, err := os.ReadFile(s.provenance)
			if err != nil {
				t.Fatalf("read provenance: %v", err)
			}
			if !strings.Contains(string(provenance), "`"+version+"`") {
				t.Errorf("%s contract advertises version %q, which %s does not record",
					s.name, version, s.provenance)
			}
		})
	}
}

// TestNormalizedCloudContractIsGenerated keeps the committed normalized document recognisable as
// generated output, so a reviewer cannot mistake it for the pristine snapshot.
func TestNormalizedCloudContractIsGenerated(t *testing.T) {
	raw, err := os.ReadFile(filepath.Join("..", "cloud", "openapi.normalized.yaml"))
	if err != nil {
		t.Fatalf("read normalized contract: %v", err)
	}
	if !strings.HasPrefix(string(raw), "# Code generated by") {
		t.Error("openapi.normalized.yaml is missing its generated-code header")
	}
}
